import { randomUUID } from 'node:crypto';
import {
  BadRequestException,
  Inject,
  Injectable,
  Logger,
  ServiceUnavailableException,
  type OnModuleInit,
} from '@nestjs/common';
import {
  CopyObjectCommand,
  CreateBucketCommand,
  DeleteObjectCommand,
  GetObjectCommand,
  HeadBucketCommand,
  HeadObjectCommand,
  PutObjectCommand,
  S3Client,
} from '@aws-sdk/client-s3';
import { getSignedUrl } from '@aws-sdk/s3-request-presigner';
import { ENV } from '../config/config.module';
import { storageEnabled, type Env } from '../config/env';

export interface ObjectMetadata {
  contentType: string;
  sizeBytes: number;
  /** ATT-2: the uploader's original filename, if the object was stored with one. */
  fileName?: string;
}

export type StorageHealth = 'ok' | 'not_configured' | 'error';

export type Visibility = 'private' | 'public';

/**
 * S3-compatible object storage. Works with **MinIO** (local dev) and
 * **Cloudflare R2** (cloud) selected via STORAGE_PROVIDER — the S3 API is the
 * same; only endpoint/region/credentials/bucket differ (all env-driven).
 *
 * Two buckets:
 *  - PRIVATE (verification documents, admin attachments): never public; access
 *    only through short-lived signed URLs generated by the API after
 *    authorization + ownership checks.
 *  - PUBLIC (future: vendor logos, public images): served via a CDN/custom-domain
 *    base URL when configured, else a signed URL. No public objects exist yet in
 *    Phase 1 — this is preparation only.
 */
@Injectable()
export class StorageService implements OnModuleInit {
  private readonly logger = new Logger(StorageService.name);
  private readonly enabled: boolean;
  private readonly client: S3Client | null;

  /**
   * MSG-2: a signed URL embeds the signing timestamp, so re-signing the same
   * key on every call hands out a different URL string for an unchanged
   * object. A client that polls (messaging, driver photos) sees its `<img
   * src>` change every call and re-fetches, even though nothing moved —
   * Oscar traced the messaging-thread flicker to exactly this. Caching the
   * minted URL per `(visibility, key)` — not per key alone, so `private` and
   * `public` can never share an entry even if a raw key string collided
   * across buckets — makes repeated reads of the same object return the
   * SAME string while that string is still comfortably valid.
   *
   * In-process only, on purpose (no Redis, per the brief): if this API ever
   * runs multiple replicas behind a load balancer, each instance keeps its
   * own cache, so a client whose polls land on different instances can
   * still see the URL change within the margin window below — not a
   * correctness or security issue (a signed URL's authorization is scoped
   * to the object and bucket, never to who signed it or who asked), just a
   * partial reduction in how stable the URL looks. Single instance: fully
   * stable. Multiple instances: still strictly better than today, where
   * EVERY call re-signs regardless of instance count.
   */
  private readonly downloadUrlCache = new Map<string, { url: string; mintedAt: number }>();
  /** Bound the cache's own memory, not the URLs' lifetime — see presignDownload. */
  private static readonly DOWNLOAD_CACHE_SWEEP_THRESHOLD = 5000;

  constructor(@Inject(ENV) private readonly env: Env) {
    this.enabled = storageEnabled(env);
    // Only construct an S3 client when storage is actually configured, so we
    // never hold localhost/minio placeholder endpoints in production.
    this.client = this.enabled
      ? new S3Client({
          region: env.STORAGE_REGION,
          endpoint: env.STORAGE_ENDPOINT,
          forcePathStyle: env.STORAGE_FORCE_PATH_STYLE,
          credentials: {
            accessKeyId: env.STORAGE_ACCESS_KEY_ID,
            secretAccessKey: env.STORAGE_SECRET_ACCESS_KEY,
          },
        })
      : null;
  }

  isEnabled(): boolean {
    return this.enabled;
  }

  private requireClient(): S3Client {
    if (!this.enabled || !this.client) {
      throw new ServiceUnavailableException(
        'Object storage is not configured. File uploads are unavailable until STORAGE_PROVIDER (e.g. r2) and its credentials are set.',
      );
    }
    return this.client;
  }

  private bucketFor(v: Visibility): string {
    return v === 'public' ? this.env.STORAGE_PUBLIC_BUCKET : this.env.STORAGE_BUCKET;
  }

  async onModuleInit(): Promise<void> {
    if (!this.enabled) {
      this.logger.warn(
        `Object storage is NOT configured (STORAGE_PROVIDER=${this.env.STORAGE_PROVIDER}, env=${this.env.NODE_ENV}). ` +
          'The API will run normally; file-upload/signed-URL endpoints return 503 until Cloudflare R2 is configured.',
      );
      return;
    }
    await this.ensureBucket('private');
    await this.ensureBucket('public');
  }

  /**
   * Report storage health for the readiness probe. Returns 'not_configured'
   * (a non-failing state) when storage is intentionally disabled.
   */
  async healthStatus(): Promise<StorageHealth> {
    if (!this.enabled || !this.client) return 'not_configured';
    try {
      await this.client.send(new HeadBucketCommand({ Bucket: this.bucketFor('private') }));
      return 'ok';
    } catch {
      return 'error';
    }
  }

  /**
   * Ensure a bucket exists. For local MinIO we create it if missing. For R2,
   * buckets are provisioned out-of-band (dashboard/API with elevated creds), so
   * we only verify reachability and warn — we never assume creation rights.
   * No-op when storage is disabled.
   */
  async ensureBucket(v: Visibility = 'private'): Promise<void> {
    if (!this.enabled || !this.client) return;
    const Bucket = this.bucketFor(v);
    try {
      await this.client.send(new HeadBucketCommand({ Bucket }));
      return;
    } catch {
      if (this.env.STORAGE_PROVIDER !== 'minio') {
        this.logger.warn(
          `Storage bucket "${Bucket}" not reachable (provider=${this.env.STORAGE_PROVIDER}); create it in the provider console.`,
        );
        return;
      }
      try {
        await this.client.send(new CreateBucketCommand({ Bucket }));
        this.logger.log(`Created ${v} storage bucket "${Bucket}".`);
      } catch (err) {
        this.logger.warn(`Bucket ensure for "${Bucket}" reported: ${String(err)}`);
      }
    }
  }

  /** Namespaced, unguessable storage key under the given owner-scoped prefix. */
  buildKey(prefix: string, fileName: string): string {
    const safe = fileName.replace(/[^\w.\-]+/g, '_').slice(-80);
    return `${prefix}/${randomUUID()}/${safe}`;
  }

  /**
   * Ownership guard: a stored key must live under the exact owner-scoped prefix
   * before we ever attach it to a record. Prevents a user from referencing
   * another user's object by guessing/replaying a key.
   */
  assertKeyInNamespace(key: string, expectedPrefix: string): void {
    if (!key.startsWith(`${expectedPrefix}/`)) {
      throw new BadRequestException('Storage key does not belong to you.');
    }
  }

  /**
   * Server-side upload: PUT an object to storage from the API process (not the
   * browser). Used for product images so the file streams browser → API (same
   * origin, via the web `/api` proxy) → storage, avoiding a cross-origin browser
   * PUT to the storage endpoint (which requires bucket CORS and fails as
   * "Load failed" on mobile Safari when the bucket doesn't allow the domain).
   */
  async putObject(
    key: string,
    body: Buffer,
    contentType: string,
    visibility: Visibility = 'private',
    // ATT-2: object metadata (S3 `x-amz-meta-*`) is the only thing that
    // survives between the upload request (where the uploader's real
    // filename is known) and whatever LATER request attaches this key to a
    // database row (where it is not, re-derivable only lossily from the
    // sanitized key `buildKey` produces). Every value here is assumed
    // pre-encoded by the caller — S3 metadata values must be valid HTTP
    // header text, which an arbitrary Unicode filename is not.
    metadata?: Record<string, string>,
  ): Promise<void> {
    const client = this.requireClient();
    await client.send(
      new PutObjectCommand({
        Bucket: this.bucketFor(visibility),
        Key: key,
        Body: body,
        ContentType: contentType,
        ContentLength: body.length,
        Metadata: metadata,
      }),
    );
  }

  /** Presigned PUT URL for a PRIVATE object the client uploads directly to. */
  async presignUpload(
    key: string,
    contentType: string,
    visibility: Visibility = 'private',
  ): Promise<{ uploadUrl: string; key: string; expiresIn: number }> {
    const client = this.requireClient();
    const command = new PutObjectCommand({
      Bucket: this.bucketFor(visibility),
      Key: key,
      ContentType: contentType,
    });
    const uploadUrl = await getSignedUrl(client, command, {
      expiresIn: this.env.STORAGE_SIGNED_URL_TTL,
    });
    return { uploadUrl, key, expiresIn: this.env.STORAGE_SIGNED_URL_TTL };
  }

  /**
   * Short-lived GET URL for viewing a PRIVATE object (admin document
   * review), or any other visibility's download URL.
   *
   * MSG-2: returns a CACHED url while it still has a healthy margin of its
   * validity window left, so repeated calls for the same `(visibility,
   * key)` are stable rather than re-signing — and re-signing a comfortable
   * margin before the real expiry rather than waiting for the boundary, so
   * nobody is ever handed a URL that is about to go dead. The margin is 60
   * seconds, or half the configured TTL if that is shorter: at the default
   * 300s TTL, a caller gets at least 240s of guaranteed-fresh validity from
   * the moment they receive a cached URL — several times Oscar's 15s poll
   * interval, comfortable headroom for a slow page load or clock skew, and
   * small enough that a dropped/restarted process loses at most one margin
   * window of staleness, never the whole cache.
   */
  async presignDownload(
    key: string,
    visibility: Visibility = 'private',
  ): Promise<{ url: string; expiresIn: number }> {
    const ttlMs = this.env.STORAGE_SIGNED_URL_TTL * 1000;
    const marginMs = Math.min(60_000, ttlMs / 2);
    const cacheKey = `${visibility}:${key}`;
    const now = Date.now();
    const cached = this.downloadUrlCache.get(cacheKey);
    if (cached && now - cached.mintedAt < ttlMs - marginMs) {
      return { url: cached.url, expiresIn: this.env.STORAGE_SIGNED_URL_TTL };
    }

    const client = this.requireClient();
    const command = new GetObjectCommand({ Bucket: this.bucketFor(visibility), Key: key });
    const url = await getSignedUrl(client, command, {
      expiresIn: this.env.STORAGE_SIGNED_URL_TTL,
    });
    this.downloadUrlCache.set(cacheKey, { url, mintedAt: now });
    // Sweep only when the cache has actually grown large, not on every
    // call — a long-running process that views many distinct objects over
    // its lifetime must not accumulate one entry per object forever. A
    // genuinely expired entry (older than the full TTL, not just past the
    // rotation margin) is always safe to drop: the next read for that key
    // simply re-signs, same as a cold cache.
    if (this.downloadUrlCache.size > StorageService.DOWNLOAD_CACHE_SWEEP_THRESHOLD) {
      for (const [k, v] of this.downloadUrlCache) {
        if (now - v.mintedAt >= ttlMs) this.downloadUrlCache.delete(k);
      }
    }
    return { url, expiresIn: this.env.STORAGE_SIGNED_URL_TTL };
  }

  /**
   * URL for a PUBLIC object: a stable CDN/custom-domain URL when configured,
   * otherwise a signed URL (dev fallback). Never used for private documents.
   */
  async publicUrl(key: string): Promise<string> {
    if (this.env.STORAGE_PUBLIC_BASE_URL) {
      return `${this.env.STORAGE_PUBLIC_BASE_URL.replace(/\/$/, '')}/${key}`;
    }
    return (await this.presignDownload(key, 'public')).url;
  }

  /**
   * Server-side copy within one bucket (S3 CopyObject; works on MinIO and R2).
   * Used to freeze an order line's image under an immutable `orders/...` key at
   * checkout, so a later product-image replace/delete (which removes the SOURCE
   * object) cannot leave order history pointing at nothing.
   */
  async copyObject(srcKey: string, dstKey: string, visibility: Visibility = 'private'): Promise<void> {
    const client = this.requireClient();
    const bucket = this.bucketFor(visibility);
    await client.send(
      new CopyObjectCommand({
        Bucket: bucket,
        // CopySource is "<bucket>/<key>", URI-encoded per the S3 API.
        CopySource: `${bucket}/${encodeURIComponent(srcKey).replace(/%2F/g, '/')}`,
        Key: dstKey,
      }),
    );
  }

  /** Delete an object. Best-effort: never throws (callers delete DB rows regardless). */
  async deleteObject(key: string, visibility: Visibility = 'private'): Promise<void> {
    if (!this.enabled || !this.client) return;
    // Order-history snapshots are immutable: nothing in the system deletes under
    // orders/ — a product-image edit deletes its own vendors/... key, never the
    // frozen copy an order line points at. Structural, not a convention.
    if (key.startsWith('orders/')) {
      this.logger.error(`Refusing to delete immutable order snapshot "${key}".`);
      return;
    }
    try {
      await this.client.send(
        new DeleteObjectCommand({ Bucket: this.bucketFor(visibility), Key: key }),
      );
    } catch (err) {
      this.logger.warn(`Failed to delete object "${key}": ${String(err)}`);
    }
  }

  /**
   * Inspect an uploaded object to read its REAL content type and size. Returns
   * null when the object does not exist. This is the source of truth for stored
   * metadata — not client-declared values.
   */
  async headObject(key: string, visibility: Visibility = 'private'): Promise<ObjectMetadata | null> {
    const client = this.requireClient();
    try {
      const res = await client.send(
        new HeadObjectCommand({ Bucket: this.bucketFor(visibility), Key: key }),
      );
      // ATT-2: S3 lower-cases metadata keys on the way back, regardless of
      // how they were sent. `decodeURIComponent` is the exact inverse of the
      // `encodeURIComponent` every writer of this metadata is required to
      // apply first; an object with no filename metadata simply has no key.
      const rawFileName = res.Metadata?.filename;
      return {
        contentType: res.ContentType ?? 'application/octet-stream',
        sizeBytes: Number(res.ContentLength ?? 0),
        fileName: rawFileName ? decodeURIComponent(rawFileName) : undefined,
      };
    } catch {
      return null;
    }
  }
}
